class Rectanglee {
private:
    int width;
    int height;
    char symbol;
    CoordOfRectangle position;

public:
    Rectanglee(int width = 0, int height = 0, char symbol = '*', CoordOfRectangle position = CoordOfRectangle()) {
        if (width < 0 || height < 0) {
            cout << "Error, width and height can`t be negative" << endl;
            this->width = 0;
            this->height = 0;
        }
        else {
            this->width = width;
            this->height = height;
        }
        this->symbol = symbol;
        this->position = position;
    }
    void draw() {
        for (int i = 0; i < position.y; i++) {
            cout << endl;
        }
        for (int i = 0; i < height; i++) {
            for (int j = 0; j < position.x; j++) {
                cout << " ";
            }
            for (int j = 0; j < width; j++) {
                cout << symbol;
            }
            cout << endl;
        }
    }
    void SetSymbol(char symbol) {
        this->symbol = symbol;
    }
    void SetPosition(CoordOfRectangle position) {
        this->position = position;
    }
    void reSize(int width, int height) {
        if (width < 0 || height < 0) {
            cout << "Error, width and height can`t be negative" << endl;
            this->width = 0;
            this->height = 0;
        }
        else {
            this->width = width;
            this->height = height;
        }
    }
    void move(int x, int y) {
        if (x < 0 || y < 0) {
            cout << "Error, coords can`t be negative" << endl;
            this->position.x = 0;
            this->position.y = 0;
        }
        else {
            this->position.x = x;
            this->position.y = y;
        }

    };
};
